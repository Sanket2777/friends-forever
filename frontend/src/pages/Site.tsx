export function SiteRouter() {
  const [location] = useLocation();
  const [lang, setLang] = useState<Lang>("en");
  const path = location.replace(/\/$/, "") || "/";

  if (path === "/") return <Home lang={lang} setLang={setLang} />;
  if (path === "/about") return <About lang={lang} setLang={setLang} />;
  if (path === "/programs") return <Programs lang={lang} setLang={setLang} />;
  if (path === "/gallery") return <Gallery lang={lang} setLang={setLang} />;
  if (path === "/contact") return <Contact lang={lang} setLang={setLang} />;
  return <NotFound lang={lang} setLang={setLang} />;
}

